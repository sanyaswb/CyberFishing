"use strict";

// npm run assets:sync (spec 157 R16, TK-178): keeps src/game/config/generated/asset_registry.js in step with the tracked
// files under assets/. The matching itself lives in src/engine/assets/asset_registry_sync.js (pure, checked without a
// file system); this tool only reads git and the files and writes the registry.
//   npm run assets:sync                       update the registry and print what changed
//   npm run assets:sync -- --check            fail if the registry is out of date (runs in Full)
//   npm run assets:sync -- --moved <old> <new>   name a move the sync cannot tell (repeatable)
//   npm run assets:sync -- --prune            drop assets whose files are gone and nothing references
//   npm run assets:sync -- --rename-id <old> <new>   rename an id in the registry and in every src/ reference
// Content hashes are the first 16 hex digits of SHA-256 (enough to tell files apart, small in the registry).

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { pathToFileURL } = require("node:url");

const ROOT = path.resolve(__dirname, "..");
const REGISTRY_FILE = "src/game/config/generated/asset_registry.js";
const ENGINE_MODULE = "src/engine/assets/asset_registry_sync.js";

function git(args) {
  const result = spawnSync("git", args, { cwd: ROOT, maxBuffer: 256 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(`git ${args.join(" ")} failed: ${result.stderr.toString("utf8").trim()}`);
  return result.stdout.toString("utf8");
}

function readOptions(argv) {
  const pairs = (flag) => argv.flatMap((value, index) => (value === flag ? [[argv[index + 1], argv[index + 2]]] : []));
  const options = { check: argv.includes("--check"), prune: argv.includes("--prune"), moved: pairs("--moved"),
    renameId: pairs("--rename-id")[0] ?? null };
  for (const [from, to] of [...options.moved, ...(options.renameId ? [options.renameId] : [])]) {
    if (!from || !to) throw new Error("--moved and --rename-id take two values");
  }
  return options;
}

function trackedAssetFiles() {
  return git(["ls-files", "-z", "assets"]).split("\0").filter(Boolean)
    .filter((file) => fs.existsSync(path.join(ROOT, file)))
    .map((file) => {
      const bytes = fs.readFileSync(path.join(ROOT, file));
      return { path: file, bytes: bytes.length, sha256: crypto.createHash("sha256").update(bytes).digest("hex").slice(0, 16) };
    });
}

// Renames git sees between the commit that last wrote the registry and the working tree.
function gitRenames() {
  const commit = git(["log", "-1", "--format=%H", "--", REGISTRY_FILE]).trim();
  if (!commit) return [];
  const fields = git(["diff", "-M", "--name-status", "-z", commit, "--", "assets"]).split("\0");
  const renames = [];
  for (let index = 0; index < fields.length; index += 1) {
    if (/^R\d*$/u.test(fields[index])) { renames.push([fields[index + 1], fields[index + 2]]); index += 2; }
  }
  return renames;
}

function sourceFiles() {
  return git(["ls-files", "-z", "src"]).split("\0").filter((file) => file.endsWith(".js") && file !== REGISTRY_FILE
    && fs.existsSync(path.join(ROOT, file)));
}

// Ids of the previous registry that src/ (code, configuration, the load plan) names as a string literal.
function referencedIds(previous) {
  const ids = new Set(Object.keys(previous));
  const found = new Set();
  for (const file of sourceFiles()) {
    for (const [, literal] of fs.readFileSync(path.join(ROOT, file), "utf8").matchAll(/["'`]([A-Za-z0-9._-]+)["'`]/gu)) {
      if (ids.has(literal)) found.add(literal);
    }
  }
  return found;
}

async function loadPrevious() {
  const file = path.join(ROOT, REGISTRY_FILE);
  if (!fs.existsSync(file)) return {};
  const module = await import(`${pathToFileURL(file).href}?read=${Date.now()}`);
  return JSON.parse(JSON.stringify(module.ASSET_REGISTRY));
}

function render(registry) {
  const value = (entry) => {
    const fields = entry.kind === "spine"
      ? [`kind: "spine"`, `json: ${JSON.stringify(entry.json)}`, `atlas: ${JSON.stringify(entry.atlas)}`,
        `textures: Object.freeze(${JSON.stringify(entry.textures)})`]
      : [`kind: ${JSON.stringify(entry.kind)}`, `path: ${JSON.stringify(entry.path)}`];
    fields.push(`bytes: ${entry.bytes}`, `sha256: ${JSON.stringify(entry.sha256)}`,
      `tags: Object.freeze(${JSON.stringify(entry.tags)})`, `label: ${JSON.stringify(entry.label)}`);
    return `Object.freeze({ ${fields.join(", ")} })`;
  };
  const lines = Object.entries(registry).map(([id, entry]) => `  ${JSON.stringify(id)}: ${value(entry)},`);
  return `// Generated by \`npm run assets:sync\` (utils/assets-sync.js; spec 157 R16, TK-178). Every asset the game shows or
// plays by its stable id: the path is where its file is now, bytes and sha256 (first 16 hex digits) are its content.
// Do not edit by hand except \`tags\` and \`label\`, which the sync keeps; a moved file keeps its id.
export const ASSET_REGISTRY = Object.freeze({
${lines.join("\n")}
});
`;
}

async function main() {
  const options = readOptions(process.argv.slice(2));
  const { collectAssets, syncAssetRegistry, atlasTextureNames } = await import(pathToFileURL(path.join(ROOT, ENGINE_MODULE)).href);
  let previous = await loadPrevious();
  if (options.renameId) previous = renameId(previous, ...options.renameId, options.check);
  const files = trackedAssetFiles();
  const atlasTextures = Object.fromEntries(files.filter((file) => file.path.endsWith(".atlas"))
    .map((file) => [file.path, atlasTextureNames(fs.readFileSync(path.join(ROOT, file.path), "utf8"))]));
  const result = syncAssetRegistry({ previous, assets: collectAssets(files, atlasTextures), moved: options.moved,
    renames: gitRenames(), referencedIds: referencedIds(previous), prune: options.prune });
  const { report, errors } = result;
  for (const [first, second] of report.duplicates) console.log(`warning: ${first} and ${second} have the same content`);
  if (errors.length > 0) throw new Error(errors.join("\n"));
  const text = render(result.registry);
  const file = path.join(ROOT, REGISTRY_FILE);
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  const summary = `${Object.keys(result.registry).length} assets: ${report.added.length} added, ${report.moved.length} moved, `
    + `${report.updated.length} updated, ${report.removed.length} removed`;
  if (options.check) {
    if (current !== text) throw new Error(`${REGISTRY_FILE} is out of date (${summary}); run npm run assets:sync`);
    console.log(`Asset registry up to date: ${summary}.`);
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (current !== text) fs.writeFileSync(file, text, "utf8");
  for (const { id, from, to } of report.moved) console.log(`moved ${id}: ${from} -> ${to}`);
  for (const id of report.added) console.log(`added ${id}`);
  for (const id of report.removed) console.log(`removed ${id}`);
  console.log(`${current === text ? "Unchanged" : "Wrote"} ${REGISTRY_FILE}: ${summary}.`);
}

// --rename-id old new: the registry entry and every string literal "old" in src/ become "new".
function renameId(previous, from, to, check) {
  if (check) throw new Error("--rename-id cannot run with --check");
  if (!previous[from]) throw new Error(`No asset ${from} in the registry`);
  if (previous[to]) throw new Error(`The id ${to} is taken`);
  const renamed = Object.fromEntries(Object.entries(previous).map(([id, entry]) => [id === from ? to : id, entry]));
  for (const file of sourceFiles()) {
    const target = path.join(ROOT, file);
    const text = fs.readFileSync(target, "utf8");
    const next = text.replace(new RegExp(`(["'\`])${from.replace(/[.]/gu, "\\.")}\\1`, "gu"), `$1${to}$1`);
    if (next !== text) { fs.writeFileSync(target, next, "utf8"); console.log(`renamed ${from} -> ${to} in ${file}`); }
  }
  return renamed;
}

if (require.main === module) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}

module.exports = { REGISTRY_FILE, render };
